let voiceAt = 0;
/* реплика соперника; force — без вероятности и паузы (поймали шулера, конец партии) */
function voiceLine(ev, force) {
  if (typeof NET !== 'undefined' && NET) return;
  if (!G || typeof currentBot !== 'function' || typeof say !== 'function') return;
  if (typeof MODE !== 'undefined' && MODE.kind === 'tutorial') return;
  const bot = currentBot(), set = bot && VOICES[bot.id];
  const list = set && set[ev];
  if (!list || !list.length) return;
  const now = Date.now();
  if (!force && (now - voiceAt < 4000 || Math.random() > 0.45)) return;
  voiceAt = now;
  const pick = list[Math.floor(Math.random() * list.length)];
  const rude = typeof rudeOn === 'function' && rudeOn();
  const t = Array.isArray(pick) ? pick[rude ? 1 : 0] : pick;
  /* чуть позже, чтобы не перебить «Беру…»/«Бито» из хода бота */
  setTimeout(() => {
    say(t);
    try { clearTimeout(sayT); sayT = setTimeout(() => $('bubble').classList.remove('on'), 2600); } catch (e) {}
  }, 450);
}

/* события партии → реплики */
if (typeof showFx === 'function') {
  const _sf = showFx;
  showFx = function (o) {
    const r = _sf.apply(this, arguments);
    try {
      if (o) {
        const bot = o.actor === 'b';
        if (o.what === 'trump') voiceLine('start', Math.random() < 0.8);
        else if (o.what === 'defend' && bot) voiceLine('cover');
        else if (o.what === 'takes' && bot) voiceLine('take');
        else if (o.what === 'transfer' && bot) voiceLine('transfer');
        else if (o.what === 'charged' && bot) voiceLine('charge');
        else if (o.what === 'hype' && o.key === 'mognul') voiceLine(bot ? 'mognulYou' : 'mognulMe', Math.random() < 0.7);
      }
    } catch (e) {}
    return r;
  };
}
if (typeof showOver === 'function') {
  const _so = showOver;
  showOver = function () {
    const r = _so.apply(this, arguments);
    try {
      if (G && G.over && G.over !== 'draw' && !G.voicedOver) { G.voicedOver = true; voiceLine(G.over === 'b' ? 'win' : 'lose', true); }
    } catch (e) {}
    return r;
  };
}
